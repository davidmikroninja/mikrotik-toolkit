const q = (text: string) => rosString(text);

function filterRule(chain: string, rule: string, commentText: string): string {
  return `/routing filter rule add chain=${rosName(chain)} rule=${q(rule)} comment=${q(
    `GEN-BGP:${commentText}`,
  )}`;
}

function lengthCondition(range: { min: number; max: number }): string {
  return range.min === range.max ? `dst-len == ${range.min}` : `dst-len in ${range.min}-${range.max}`;
}

function numOr(value: string, fallback: number): number {
  return parseInteger(value) ?? fallback;
}

function transactionPrefixes(config: Config): { v4: string[]; v6: string[] } {
  const v4 = uniqueSorted(
    config.addressFamilies.ipv4.prefixes
      .map((prefix) => normalizePrefix(prefix))
      .filter((prefix): prefix is string => Boolean(prefix)),
  );
  const v6 = config.addressFamilies.ipv6.enabled
    ? uniqueSorted(
        config.addressFamilies.ipv6.prefixes
          .map((prefix) => normalizePrefix(prefix))
          .filter((prefix): prefix is string => Boolean(prefix)),
      )
    : [];
  return { v4, v6 };
}

function rpkiGroupForFabric(config: Config, fabric: FabricId): RpkiGroupConfig | undefined {
  if (!config.rpki.enabled) return undefined;
  return config.rpki.groups.find(
    (group) => group.enabled && group.groupName === FABRICS[fabric].rpkiGroup,
  );
}

function rpkiGroupForTransit(config: Config): RpkiGroupConfig | undefined {
  if (!config.rpki.enabled || !config.rpki.enforceOnTransits) return undefined;
  return config.rpki.groups.find((group) => group.enabled);
}

function cleanupCommands(): string {
  return lines(
    '# --- Remove objects generated by the previous run ---------------------------',
    '/routing/bgp/connection remove [find where name~"^gen-"]',
    '/routing/bgp/template remove [find where name~"^gen-"]',
    '/routing/bgp/instance remove [find where name~"^gen-"]',
    '/routing/filter/rule remove [find where comment~"^GEN-BGP:"]',
    '/ip firewall address-list remove [find where comment~"^GEN-BGP:network"]',
    '/ipv6 firewall address-list remove [find where comment~"^GEN-BGP:network"]',
    '/ip route remove [find where comment~"^GEN-BGP:blackhole"]',
    '/ipv6 route remove [find where comment~"^GEN-BGP:blackhole"]',
  );
}

const BGP_INSTANCE = 'gen-main';

function instanceCommands(localAsn: number, routerId: string): string {
  return lines(
    '# --- BGP instance -----------------------------------------------------------',
    '# RouterOS 7.20+ requires an instance on every connection and no longer',
    '# accepts router-id on a template/connection. The instance holds both.',
    `/routing/bgp/instance add name=${BGP_INSTANCE} as=${localAsn} router-id=${routerId} routing-table=main`,
  );
}

function networkCommands(prefixes: { v4: string[]; v6: string[] }): string {
  const commands: string[] = ['# --- Originated networks ----------------------------------------------------'];
  prefixes.v4.forEach((prefix) => {
    commands.push(
      `:if ([:len [/ip firewall address-list find where list=${q('bgp-networks-v4')} and address=${q(prefix)}]] = 0) do={ /ip firewall address-list add list=${q('bgp-networks-v4')} address=${q(prefix)} comment=${q(`GEN-BGP:network ${prefix}`)} }`,
    );
    commands.push(
      `:if ([:len [/ip route find where dst-address=${q(prefix)}]] = 0) do={ /ip route add dst-address=${q(prefix)} blackhole comment=${q(`GEN-BGP:blackhole ${prefix}`)} }`,
    );
  });
  prefixes.v6.forEach((prefix) => {
    commands.push(
      `:if ([:len [/ipv6 firewall address-list find where list=${q('bgp-networks-v6')} and address=${q(prefix)}]] = 0) do={ /ipv6 firewall address-list add list=${q('bgp-networks-v6')} address=${q(prefix)} comment=${q(`GEN-BGP:network ${prefix}`)} }`,
    );
    commands.push(
      `:if ([:len [/ipv6 route find where dst-address=${q(prefix)}]] = 0) do={ /ipv6 route add dst-address=${q(prefix)} blackhole comment=${q(`GEN-BGP:blackhole ${prefix}`)} }`,
    );
  });
  if (commands.length === 1) commands.push('# No prefixes configured.');
  return lines(...commands);
}

function rpkiCommands(config: Config): string {
  if (!config.rpki.enabled) return '';
  const entries: string[] = [];
  const seen = new Set<string>();
  config.rpki.groups
    .filter((group) => group.enabled)
    .forEach((group) => {
      group.servers.forEach((server) => {
        const key = `${server}|${group.port}|${group.groupName}`;
        if (seen.has(key)) return;
        seen.add(key);
        entries.push(
          `:if ([:len [/routing rpki find where address=${q(server)} and port=${group.port} and group=${q(group.groupName)}]] = 0) do={ /routing rpki add address=${q(server)} port=${group.port} group=${q(group.groupName)} }`,
        );
      });
    });
  if (entries.length === 0) return '';
  return lines('# --- RPKI RTR servers -------------------------------------------------------', ...entries);
}

function bogonCommands(): string {
  const v4 = [
    '0.0.0.0/8',
    '10.0.0.0/8',
    '100.64.0.0/10',
    '127.0.0.0/8',
    '169.254.0.0/16',
    '172.16.0.0/12',
    '192.0.0.0/24',
    '192.0.2.0/24',
    '192.88.99.0/24',
    '192.168.0.0/16',
    '198.18.0.0/15',
    '198.51.100.0/24',
    '203.0.113.0/24',
    '224.0.0.0/3',
  ];
  const v6 = [
    '::/0',
    '::/96',
    '::/8',
    '100::/64',
    '200::/7',
    '2001:2::/48',
    '2001:10::/28',
    '2001:20::/28',
    '2001:db8::/32',
    '3ffe::/16',
    'fc00::/7',
    'fe80::/10',
    'fec0::/10',
    'ff00::/8',
  ];

  const commands: string[] = [
    '# --- Bogon / martian filters ------------------------------------------------',
    filterRule('gen-rfc5735', 'if (dst == 0.0.0.0/0) { reject; }', 'rfc5735 default'),
    ...v4
      .filter((prefix) => prefix !== '0.0.0.0/0')
      .map((prefix) => filterRule('gen-rfc5735', `if (dst in ${prefix}) { reject; }`, `rfc5735 ${prefix}`)),
    filterRule('gen-rfc5735', 'return;', 'rfc5735 return'),
  ];
  commands.push(
    filterRule('gen-ipv6martian', 'if (dst == ::/0) { reject; }', 'ipv6 martian default'),
    ...v6
      .filter((prefix) => prefix !== '::/0')
      .map((prefix) =>
        filterRule('gen-ipv6martian', `if (dst in ${prefix}) { reject; }`, `ipv6 martian ${prefix}`),
      ),
    filterRule('gen-ipv6martian', 'return;', 'ipv6 martian return'),
  );
  return lines(...commands);
}

function outputCommands(
  prefixes: { v4: string[]; v6: string[] },
  ranges: { v4: { min: number; max: number }; v6: { min: number; max: number } },
  hasBackupTransit: boolean,
): string {
  const commands: string[] = ['# --- Outbound advertisement filters -----------------------------------------'];
  if (prefixes.v4.length > 0) {
    commands.push(
      filterRule(
        'gen-out-v4',
        `if (dst in bgp-networks-v4 && ${lengthCondition(ranges.v4)}) { accept; }`,
        'advertise v4',
      ),
      filterRule('gen-out-v4', 'reject;', 'discard other v4'),
    );
    if (hasBackupTransit) {
      commands.push(
        filterRule(
          'gen-out-backup-v4',
          `if (dst in bgp-networks-v4 && ${lengthCondition(ranges.v4)}) { set bgp-path-prepend 3; accept; }`,
          'advertise v4 with prepend',
        ),
        filterRule('gen-out-backup-v4', 'reject;', 'discard other v4 (backup)'),
      );
    }
  }
  if (prefixes.v6.length > 0) {
    commands.push(
      filterRule(
        'gen-out-v6',
        `if (dst in bgp-networks-v6 && ${lengthCondition(ranges.v6)}) { accept; }`,
        'advertise v6',
      ),
      filterRule('gen-out-v6', 'reject;', 'discard other v6'),
    );
    if (hasBackupTransit) {
      commands.push(
        filterRule(
          'gen-out-backup-v6',
          `if (dst in bgp-networks-v6 && ${lengthCondition(ranges.v6)}) { set bgp-path-prepend 3; accept; }`,
          'advertise v6 with prepend',
        ),
        filterRule('gen-out-backup-v6', 'reject;', 'discard other v6 (backup)'),
      );
    }
  }
  return lines(...commands);
}

interface InputChainOptions {
  chain: string;
  rpkiGroup?: RpkiGroupConfig;
  defaultPrefix?: string;
  defaultLocalPref?: number;
  routesLocalPref: number;
  ownList: string;
  bogonChain: string;
  rejectLongerThan?: number;
  label: string;
}

function inputChainRules(options: InputChainOptions): string[] {
  const rules: string[] = [];
  if (options.rpkiGroup) {
    rules.push(
      filterRule(options.chain, `rpki-verify ${options.rpkiGroup.groupName}`, `${options.label} rpki verify`),
    );
    rules.push(filterRule(options.chain, 'if (rpki invalid) { reject; }', `${options.label} rpki invalid`));
  }
  if (options.defaultPrefix && options.defaultLocalPref !== undefined) {
    rules.push(
      filterRule(
        options.chain,
        `if (dst == ${options.defaultPrefix}) { set bgp-local-pref ${options.defaultLocalPref}; accept; }`,
        `${options.label} default route`,
      ),
    );
  }
  rules.push(filterRule(options.chain, `jump ${options.bogonChain};`, `${options.label} bogon`));
  rules.push(
    filterRule(
      options.chain,
      `if (dst in ${options.ownList}) { reject; }`,
      `${options.label} own prefix`,
    ),
  );
  if (options.rejectLongerThan !== undefined) {
    rules.push(
      filterRule(
        options.chain,
        `if (dst-len > ${options.rejectLongerThan}) { reject; }`,
        `${options.label} prefix length`,
      ),
    );
  }
  rules.push(
    filterRule(
      options.chain,
      `set bgp-local-pref ${options.routesLocalPref}; accept`,
      `${options.label} accept`,
    ),
  );
  return rules;
}

function transitChains(
  config: Config,
  transit: Transit,
  prefixes: { v4: string[]; v6: string[] },
  reject: { v4?: number; v6?: number },
): string {
  const name = slug(transit.name);
  const rpki = rpkiGroupForTransit(config);
  const defaultLocalPref =
    parseInteger(transit.defaultLocalPref) ??
    numOr(
      transit.kind === 'primary' ? config.priorities.transitDefault : config.priorities.transitBackupDefault,
      transit.kind === 'primary' ? 110 : 100,
    );
  const routesLocalPref =
    parseInteger(transit.routesLocalPref) ??
    numOr(
      transit.kind === 'primary' ? config.priorities.transitRoutes : config.priorities.transitBackupRoutes,
      transit.kind === 'primary' ? 130 : 120,
    );
  const commands: string[] = [`# Transit ${transit.name} (${transit.kind})`];
  if (prefixes.v4.length > 0 && transit.v4.trim()) {
    commands.push(
      ...inputChainRules({
        chain: `gen-ipt-in-v4-${name}`,
        rpkiGroup: rpki,
        defaultPrefix: transit.defaultRoute ? '0.0.0.0/0' : undefined,
        defaultLocalPref: transit.defaultRoute ? defaultLocalPref : undefined,
        routesLocalPref,
        ownList: 'bgp-networks-v4',
        bogonChain: 'gen-rfc5735',
        rejectLongerThan: reject.v4,
        label: `${transit.name} v4`,
      }),
    );
  }
  if (prefixes.v6.length > 0 && transit.v6.trim()) {
    commands.push(
      ...inputChainRules({
        chain: `gen-ipt-in-v6-${name}`,
        rpkiGroup: rpki,
        defaultPrefix: transit.defaultRoute ? '::/0' : undefined,
        defaultLocalPref: transit.defaultRoute ? defaultLocalPref : undefined,
        routesLocalPref,
        ownList: 'bgp-networks-v6',
        bogonChain: 'gen-ipv6martian',
        rejectLongerThan: reject.v6,
        label: `${transit.name} v6`,
      }),
    );
  }
  return lines(...commands);
}

function fabricChains(
  config: Config,
  fabric: FabricId,
  prefixes: { v4: string[]; v6: string[] },
  reject: { v4?: number; v6?: number },
  hasNap: boolean,
  hasBlp: boolean,
): string {
  const commands: string[] = [];
  const rpki = rpkiGroupForFabric(config, fabric);
  const napPref = numOr(
    fabric === 'ct' ? config.priorities.napCt : config.priorities.napJb,
    FABRICS[fabric].defaultLocalPref,
  );
  const blpPref = numOr(
    fabric === 'ct' ? config.priorities.blpCt : config.priorities.blpJb,
    FABRICS[fabric].defaultLocalPref + 100,
  );

  if (hasNap) {
    if (prefixes.v4.length > 0) {
      commands.push(
        ...inputChainRules({
          chain: `gen-nap-${fabric}-in-v4`,
          rpkiGroup: rpki,
          routesLocalPref: napPref,
          ownList: 'bgp-networks-v4',
          bogonChain: 'gen-rfc5735',
          rejectLongerThan: reject.v4,
          label: `${FABRICS[fabric].shortLabel} route server v4`,
        }),
      );
    }
    if (prefixes.v6.length > 0) {
      commands.push(
        ...inputChainRules({
          chain: `gen-nap-${fabric}-in-v6`,
          rpkiGroup: rpki,
          routesLocalPref: napPref,
          ownList: 'bgp-networks-v6',
          bogonChain: 'gen-ipv6martian',
          rejectLongerThan: reject.v6,
          label: `${FABRICS[fabric].shortLabel} route server v6`,
        }),
      );
    }
  }

  if (hasBlp) {
    if (prefixes.v4.length > 0) {
      commands.push(
        ...inputChainRules({
          chain: `gen-blp-${fabric}-in-v4`,
          rpkiGroup: rpki,
          routesLocalPref: blpPref,
          ownList: 'bgp-networks-v4',
          bogonChain: 'gen-rfc5735',
          rejectLongerThan: reject.v4,
          label: `${FABRICS[fabric].shortLabel} bilateral v4`,
        }),
      );
    }
    if (prefixes.v6.length > 0) {
      commands.push(
        ...inputChainRules({
          chain: `gen-blp-${fabric}-in-v6`,
          rpkiGroup: rpki,
          routesLocalPref: blpPref,
          ownList: 'bgp-networks-v6',
          bogonChain: 'gen-ipv6martian',
          rejectLongerThan: reject.v6,
          label: `${FABRICS[fabric].shortLabel} bilateral v6`,
        }),
      );
    }
  }

  return commands.length > 0 ? lines(...commands) : '';
}

function customPeerChains(
  config: Config,
  peer: CustomPeer,
  prefixes: { v4: string[]; v6: string[] },
  reject: { v4?: number; v6?: number },
): string {
  const name = slug(peer.name);
  const rpki = rpkiGroupForFabric(config, peer.fabric);
  const localPref = parseInteger(peer.localPref) ?? numOr(
    peer.fabric === 'ct' ? config.priorities.blpCt : config.priorities.blpJb,
    400,
  );
  const commands: string[] = [`# Custom peer ${peer.name}`];
  if (prefixes.v4.length > 0 && peer.v4.trim()) {
    commands.push(
      ...inputChainRules({
        chain: `gen-peer-in-v4-${name}`,
        rpkiGroup: rpki,
        routesLocalPref: localPref,
        ownList: 'bgp-networks-v4',
        bogonChain: 'gen-rfc5735',
        rejectLongerThan: reject.v4,
        label: `${peer.name} v4`,
      }),
    );
  }
  if (prefixes.v6.length > 0 && peer.v6.trim()) {
    commands.push(
      ...inputChainRules({
        chain: `gen-peer-in-v6-${name}`,
        rpkiGroup: rpki,
        routesLocalPref: localPref,
        ownList: 'bgp-networks-v6',
        bogonChain: 'gen-ipv6martian',
        rejectLongerThan: reject.v6,
        label: `${peer.name} v6`,
      }),
    );
  }
  return lines(...commands);
}

interface TemplateOptions {
  name: string;
  commentText: string;
  asn: number;
  afi: 'ip' | 'ipv6';
  inputFilter: string;
  outputFilter: string;
  networkList: string;
  maxPrefixes?: number;
}

function templateCommand(options: TemplateOptions): string {
  const afi = options.afi;
  const limit =
    afi === 'ip'
      ? options.maxPrefixes !== undefined
        ? ` input.limit-process-routes-ipv4=${options.maxPrefixes}`
        : ''
      : options.maxPrefixes !== undefined
        ? ` input.limit-process-routes-ipv6=${options.maxPrefixes}`
        : '';
  return `/routing/bgp/template add name=${options.name} comment=${q(
    `GEN-BGP:${options.commentText}`,
  )} as=${options.asn} afi=${afi} routing-table=main input.filter=${options.inputFilter} output.filter-chain=${options.outputFilter} output.network=${options.networkList}${limit} disabled=no`;
}

interface ConnectionOptions {
  name: string;
  address: string;
  asn: number;
  template: string;
  role: string;
}

function connectionCommand(options: ConnectionOptions): string {
  return `/routing/bgp/connection add name=${options.name} instance=${BGP_INSTANCE} connect=yes listen=yes local.role=${options.role} remote.address=${options.address} remote.as=${options.asn} templates=${options.template} disabled=no`;
}

function defaultMaxPrefixes(kind: 'transit' | 'route-server' | 'bilateral', afi: 'ip' | 'ipv6', peer?: CustomPeer): number | undefined {
  const fallback =
    kind === 'transit' || kind === 'route-server'
      ? afi === 'ip'
        ? 1_500_000
        : 300_000
      : afi === 'ip'
        ? 250_000
        : 100_000;
  if (peer) {
    const value = afi === 'ip' ? peer.maxPrefixesV4 : peer.maxPrefixesV6;
    return parseInteger(value) ?? fallback;
  }
  return fallback;
}

export function generateBgpFile(config: Config, meta: GenerationMeta): GeneratedFile {
  const prefixes = transactionPrefixes(config);
  const ranges = {
    v4: parseLengthRange(config.addressFamilies.ipv4.advertiseLengths, 32) ?? { min: 0, max: 32 },
    v6: parseLengthRange(config.addressFamilies.ipv6.advertiseLengths, 128) ?? { min: 0, max: 128 },
  };
  const reject = {
    v4: config.addressFamilies.ipv4.rejectLongerThan.trim()
      ? parseInteger(config.addressFamilies.ipv4.rejectLongerThan) ?? undefined
      : undefined,
    v6: config.addressFamilies.ipv6.enabled && config.addressFamilies.ipv6.rejectLongerThan.trim()
      ? parseInteger(config.addressFamilies.ipv6.rejectLongerThan) ?? undefined
      : undefined,
  };
  const routerId = config.router.routerId.trim();
  const localAsn = parseInteger(config.router.asn) ?? 0;
  const hasV4 = prefixes.v4.length > 0;
  const hasV6 = prefixes.v6.length > 0;

  const transits = [...config.transits].sort((a, b) =>
    a.name.localeCompare(b.name, 'en'),
  );
  const hasBackupTransit = transits.some((transit) => transit.kind === 'backup');

  const fabricData = (['ct', 'jb'] as const).map((fabric) => {
    const selection = config.peering[fabric];
    const groups = [...new Set(selection.bilaterals)]
      .map((groupId) => findPeerGroup(groupId))
      .filter((group): group is NonNullable<ReturnType<typeof findPeerGroup>> => Boolean(group));
    const customPeers = config.peering.customPeers.filter((peer) => peer.fabric === fabric);
    return {
      fabric,
      selection,
      groups,
      customPeers,
      hasNap: selection.routeServers,
      hasBlp: groups.length > 0,
    };
  });

  const chainSections: string[] = [];
  transits.forEach((transit) => {
    if (!transit.name.trim()) return;
    chainSections.push(transitChains(config, transit, prefixes, reject));
  });
  fabricData.forEach((data) => {
    if (!data.hasNap && !data.hasBlp) return;
    chainSections.push(
      fabricChains(config, data.fabric, prefixes, reject, data.hasNap, data.hasBlp),
    );
  });
  fabricData.forEach((data) => {
    data.customPeers.forEach((peer) => {
      if (!peer.name.trim()) return;
      chainSections.push(customPeerChains(config, peer, prefixes, reject));
    });
  });

  const templates: string[] = ['# --- BGP templates ----------------------------------------------------------'];
  transits.forEach((transit) => {
    if (!transit.name.trim()) return;
    const name = slug(transit.name);
    const output = transit.kind === 'backup' ? 'gen-out-backup' : 'gen-out';
    const transitAsn = parseInteger(transit.asn);
    if (transitAsn === null) return;
    if (hasV4 && transit.v4.trim()) {
      templates.push(
        templateCommand({
          name: `gen-ipt-v4-${name}`,
          commentText: `transit ${transit.name} v4`,
          asn: localAsn,
          afi: 'ip',
          inputFilter: `gen-ipt-in-v4-${name}`,
          outputFilter: `${output}-v4`,
          networkList: 'bgp-networks-v4',
          maxPrefixes:
            parseInteger(transit.maxPrefixesV4) ??
            defaultMaxPrefixes('transit', 'ip'),
        }),
      );
    }
    if (hasV6 && transit.v6.trim()) {
      templates.push(
        templateCommand({
          name: `gen-ipt-v6-${name}`,
          commentText: `transit ${transit.name} v6`,
          asn: localAsn,
          afi: 'ipv6',
          inputFilter: `gen-ipt-in-v6-${name}`,
          outputFilter: `${output}-v6`,
          networkList: 'bgp-networks-v6',
          maxPrefixes:
            parseInteger(transit.maxPrefixesV6) ??
            defaultMaxPrefixes('transit', 'ipv6'),
        }),
      );
    }
  });

  fabricData.forEach((data) => {
    if (data.hasNap) {
      if (hasV4) {
        templates.push(
          templateCommand({
            name: `gen-nap-${data.fabric}-v4`,
            commentText: `${FABRICS[data.fabric].shortLabel} route servers v4`,
            asn: localAsn,
            afi: 'ip',
              inputFilter: `gen-nap-${data.fabric}-in-v4`,
            outputFilter: 'gen-out-v4',
            networkList: 'bgp-networks-v4',
            maxPrefixes: defaultMaxPrefixes('route-server', 'ip'),
          }),
        );
      }
      if (hasV6) {
        templates.push(
          templateCommand({
            name: `gen-nap-${data.fabric}-v6`,
            commentText: `${FABRICS[data.fabric].shortLabel} route servers v6`,
            asn: localAsn,
            afi: 'ipv6',
              inputFilter: `gen-nap-${data.fabric}-in-v6`,
            outputFilter: 'gen-out-v6',
            networkList: 'bgp-networks-v6',
            maxPrefixes: defaultMaxPrefixes('route-server', 'ipv6'),
          }),
        );
      }
    }
    if (data.hasBlp) {
      if (hasV4) {
        templates.push(
          templateCommand({
            name: `gen-blp-${data.fabric}-v4`,
            commentText: `${FABRICS[data.fabric].shortLabel} bilateral peers v4`,
            asn: localAsn,
            afi: 'ip',
              inputFilter: `gen-blp-${data.fabric}-in-v4`,
            outputFilter: 'gen-out-v4',
            networkList: 'bgp-networks-v4',
            maxPrefixes: defaultMaxPrefixes('bilateral', 'ip'),
          }),
        );
      }
      if (hasV6) {
        templates.push(
          templateCommand({
            name: `gen-blp-${data.fabric}-v6`,
            commentText: `${FABRICS[data.fabric].shortLabel} bilateral peers v6`,
            asn: localAsn,
            afi: 'ipv6',
              inputFilter: `gen-blp-${data.fabric}-in-v6`,
            outputFilter: 'gen-out-v6',
            networkList: 'bgp-networks-v6',
            maxPrefixes: defaultMaxPrefixes('bilateral', 'ipv6'),
          }),
        );
      }
    }
    data.customPeers.forEach((peer) => {
      if (!peer.name.trim()) return;
      const name = slug(peer.name);
      const peerAsn = parseInteger(peer.asn);
      if (peerAsn === null) return;
      if (hasV4 && peer.v4.trim()) {
        templates.push(
          templateCommand({
            name: `gen-peer-v4-${name}`,
            commentText: `peer ${peer.name} v4`,
            asn: localAsn,
            afi: 'ip',
              inputFilter: `gen-peer-in-v4-${name}`,
            outputFilter: 'gen-out-v4',
            networkList: 'bgp-networks-v4',
            maxPrefixes: defaultMaxPrefixes('bilateral', 'ip', peer),
          }),
        );
      }
      if (hasV6 && peer.v6.trim()) {
        templates.push(
          templateCommand({
            name: `gen-peer-v6-${name}`,
            commentText: `peer ${peer.name} v6`,
            asn: localAsn,
            afi: 'ipv6',
              inputFilter: `gen-peer-in-v6-${name}`,
            outputFilter: 'gen-out-v6',
            networkList: 'bgp-networks-v6',
            maxPrefixes: defaultMaxPrefixes('bilateral', 'ipv6', peer),
          }),
        );
      }
    });
  });

  const connections: string[] = ['# --- BGP sessions -----------------------------------------------------------'];
  transits.forEach((transit) => {
    const transitAsn = parseInteger(transit.asn);
    if (transitAsn === null) return;
    const name = slug(transit.name);
    const role = transit.role === 'provider' ? 'ebgp-provider' : 'ebgp-customer';
    if (hasV4 && transit.v4.trim()) {
      connections.push(
        connectionCommand({
          name: `gen-ipt-${name}-v4`,
          address: transit.v4.trim(),
          asn: transitAsn,
          template: `gen-ipt-v4-${name}`,
          role,
        }),
      );
    }
    if (hasV6 && transit.v6.trim()) {
      connections.push(
        connectionCommand({
          name: `gen-ipt-${name}-v6`,
          address: transit.v6.trim(),
          asn: transitAsn,
          template: `gen-ipt-v6-${name}`,
          role,
        }),
      );
    }
  });

  fabricData.forEach((data) => {
    if (data.hasNap) {
      FABRICS[data.fabric].routeServers.forEach((session) => {
        if (hasV4) {
          connections.push(
            connectionCommand({
              name: `gen-nap-${data.fabric}-${session.label}-v4`,
              address: session.v4,
              asn: session.asn,
              template: `gen-nap-${data.fabric}-v4`,
              role: 'ebgp-rs-client',
            }),
          );
        }
        if (hasV6) {
          connections.push(
            connectionCommand({
              name: `gen-nap-${data.fabric}-${session.label}-v6`,
              address: session.v6,
              asn: session.asn,
              template: `gen-nap-${data.fabric}-v6`,
              role: 'ebgp-rs-client',
            }),
          );
        }
      });
    }
    data.groups.forEach((group) => {
      group.sessions.forEach((session) => {
        if (hasV4 && session.v4) {
          connections.push(
            connectionCommand({
              name: `gen-blp-${data.fabric}-${group.id}-${session.label}-v4`,
              address: session.v4,
              asn: group.asn,
              template: `gen-blp-${data.fabric}-v4`,
              role: 'ebgp-peer',
            }),
          );
        }
        if (hasV6 && session.v6) {
          connections.push(
            connectionCommand({
              name: `gen-blp-${data.fabric}-${group.id}-${session.label}-v6`,
              address: session.v6,
              asn: group.asn,
              template: `gen-blp-${data.fabric}-v6`,
              role: 'ebgp-peer',
            }),
          );
        }
      });
    });
    data.customPeers.forEach((peer) => {
      const peerAsn = parseInteger(peer.asn);
      if (peerAsn === null) return;
      const name = slug(peer.name);
      if (hasV4 && peer.v4.trim()) {
        connections.push(
          connectionCommand({
            name: `gen-peer-${name}-v4`,
            address: peer.v4.trim(),
            asn: peerAsn,
            template: `gen-peer-v4-${name}`,
            role: 'ebgp-peer',
          }),
        );
      }
      if (hasV6 && peer.v6.trim()) {
        connections.push(
          connectionCommand({
            name: `gen-peer-${name}-v6`,
            address: peer.v6.trim(),
            asn: peerAsn,
            template: `gen-peer-v6-${name}`,
            role: 'ebgp-peer',
          }),
        );
      }
    });
  });

  const sessionCount = connections.filter((line) => line.startsWith('/routing/bgp/connection')).length;
  const notes: string[] = [
    `RouterOS 7.20+ syntax (afi=ip / afi=ipv6). ${sessionCount} BGP session(s) generated.`,
    'Outbound announcements come from gen-out-v4/v6; backup transits prepend AS3.',
    'Blackhole routes are added only when no route already exists for the prefix.',
  ];
  if (config.rpki.enabled) {
    notes.push('RPKI validation is applied to input chains where a group is enabled.');
  }
  if (transits.length === 0 && sessionCount === 0) {
    notes.push('No transit or peering sessions were selected.');
  }

  const chainBody =
    chainSections.length > 0
      ? lines('# --- Inbound filters --------------------------------------------------------', ...chainSections)
      : '';
  const templateBody =
    templates.length > 1 ? lines(...templates) : '# No BGP templates generated.';
  const connectionBody =
    connections.length > 1 ? lines(...connections) : '# No BGP sessions generated.';

  const content = lines(
    generatedHeader(meta, 'BGP configuration', notes),
    cleanupCommands(),
    instanceCommands(localAsn, routerId),
    networkCommands(prefixes),
    rpkiCommands(config),
    bogonCommands(),
    outputCommands(prefixes, ranges, hasBackupTransit),
    chainBody,
    templateBody,
    connectionBody,
    '#',
    '# Bilateral sessions are opt-in and should only be enabled with an agreed',
    '# peering relationship. Verify with: /routing/bgp/session print',
    ':log info "GEN: BGP imported"',
  );

  return {
    name: '20-bgp.rsc',
    content: content + '\n',
    language: 'routeros',
    description: 'Filters, RPKI, templates and sessions for transits, IXP and bilateral peers.',
  };
}
